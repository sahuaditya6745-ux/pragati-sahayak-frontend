/**
 * Filter competitors by location and category.
 * If exact block matches are found, return them.
 * If no block matches exist, fall back to matching district to provide useful nearby comparisons.
 */
export function getCompetitors({ state, district, block, categoryId } = {}) {
  const safeState = typeof state === "string" ? state.trim().toLowerCase() : "";
  const safeDistrict = typeof district === "string" ? district.trim().toLowerCase() : "";
  const safeBlock = typeof block === "string" ? block.trim().toLowerCase() : "";
  const safeCategory = typeof categoryId === "string" ? categoryId.trim() : (categoryId || "");

  if (!safeState && !safeDistrict && !safeBlock && !safeCategory) {
    return COMPETITORS;
  }

  // 1. Exact match (State + District + Block + Category)
  const exactBlockMatches = COMPETITORS.filter((c) => {
    const cState = (c.state || "").toLowerCase();
    const cDistrict = (c.district || "").toLowerCase();
    const cBlock = (c.block || "").toLowerCase();
    const matchState = !safeState || cState === safeState;
    const matchDistrict = !safeDistrict || cDistrict === safeDistrict;
    const matchBlock = !safeBlock || cBlock === safeBlock;
    const matchCategory = !safeCategory || c.category_id === safeCategory;
    return matchState && matchDistrict && matchBlock && matchCategory;
  });

  if (exactBlockMatches.length > 0) {
    return exactBlockMatches;
  }

  // 2. District level fallback if category matches
  if (safeDistrict && safeCategory) {
    const districtMatches = COMPETITORS.filter((c) => {
      const cState = (c.state || "").toLowerCase();
      const cDistrict = (c.district || "").toLowerCase();
      const matchState = !safeState || cState === safeState;
      const matchDistrict = cDistrict === safeDistrict;
      const matchCategory = c.category_id === safeCategory;
      return matchState && matchDistrict && matchCategory;
    });

    if (districtMatches.length > 0) {
      return districtMatches;
    }
  }

  return [];
}

export function countCompetitors(state, district, block, categoryId) {
  return getCompetitors({ state, district, block, categoryId }).length;
}

